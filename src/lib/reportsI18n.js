const DICTIONARIES = { en, ml, kn };

function readStoredLanguage() {
  try {
    const value = window.localStorage.getItem(STORAGE_KEY);
    return DICTIONARIES[value] ? value : "en";
  } catch {
    return "en";
  }
}

/** Builds the helpers for one language: t(), month names, money. */
export function reportsText(lang) {
  const dict = DICTIONARIES[lang] || en;
  const locale = REPORT_LANGUAGES.find((l) => l.code === lang)?.locale || "en-IN";
  const t = (key, vars) => {
    if (key === "monthCount" && Number(vars?.n) === 1) key = "monthCountOne";
    let text = dict[key] ?? en[key] ?? key;
    if (vars && typeof text === "string") {
      Object.entries(vars).forEach(([name, value]) => { text = text.split(`{${name}}`).join(String(value)); });
    }
    return text;
  };
  const monthFmt = new Intl.DateTimeFormat(locale, { month: "short", year: "numeric", timeZone: "UTC" });
  const longMonthFmt = new Intl.DateTimeFormat(locale, { month: "long", year: "numeric", timeZone: "UTC" });
  const monthOnlyFmt = new Intl.DateTimeFormat(locale, { month: "short", timeZone: "UTC" });
  const dateFmt = new Intl.DateTimeFormat(locale, { day: "numeric", month: "short", year: "numeric", timeZone: "UTC" });
  const toUtc = (month) => new Date(`${month}-01T00:00:00Z`);
  return {
    lang,
    locale,
    t,
    /** "2026-10" -> "Oct 2026" in the chosen language */
    month: (m) => (m ? monthFmt.format(toUtc(m)) : "—"),
    longMonth: (m) => (m ? longMonthFmt.format(toUtc(m)) : "—"),
    monthOnly: (m) => (m ? monthOnlyFmt.format(toUtc(m)) : ""),
    /** "2026-10-05" -> "5 Oct 2026" */
    date: (d) => (d ? dateFmt.format(new Date(`${String(d).slice(0, 10)}T00:00:00Z`)) : "—"),
    /** Short list: up to 4 months by name; longer runs as "Aug 2024 – Nov 2026 (28)". */
    monthList: (months = []) => {
      if (months.length <= 4) return months.map((m) => monthFmt.format(toUtc(m))).join(", ");
      const contiguous = months.every((m, i) => {
        if (!i) return true;
        const [y, mo] = months[i - 1].split("-").map(Number);
        const next = mo === 12 ? `${y + 1}-01` : `${y}-${String(mo + 1).padStart(2, "0")}`;
        return m === next;
      });
      if (contiguous) return `${monthFmt.format(toUtc(months[0]))} – ${monthFmt.format(toUtc(months[months.length - 1]))} (${months.length})`;
      return `${months.slice(0, 3).map((m) => monthFmt.format(toUtc(m))).join(", ")} … +${months.length - 3}`;
    },
    money: (n) => `₹${Number(n || 0).toLocaleString("en-IN", { maximumFractionDigits: 2 })}`,
    stateLabel: (state) => ({
      paid: t("paid"), waiting: t("waitingShort"), not_paid: t("notPaid"), rejected: t("rejected"),
      before_join: t("beforeJoin"), future: t("future"),
    }[state] || state),
    method: (m) => (m ? (dict.methods?.[String(m).toLowerCase()] || en.methods[String(m).toLowerCase()] || String(m)) : "—"),
  };
}

/** The chosen language, remembered on this device. */
export function useReportsLanguage() {
  const [lang, setLangState] = useState(readStoredLanguage);
  useEffect(() => {
    try { window.localStorage.setItem(STORAGE_KEY, lang); } catch { /* optional */ }
  }, [lang]);
  const setLang = useCallback((value) => setLangState(DICTIONARIES[value] ? value : "en"), []);
  return { ...reportsText(lang), setLang };
}

