const DICT = { en, ml, kn };

/** Reports' language helpers (money, dates, switch) plus the relief words. */
export function useReliefText() {
  const L = useReportsLanguage();
  const dict = DICT[L.lang] || en;
  const t = useCallback((key, vars) => {
    let text = dict[key] ?? en[key];
    if (text === undefined) return L.t(key, vars);
    if (vars) Object.entries(vars).forEach(([k, v]) => { text = text.split(`{${k}}`).join(String(v)); });
    return text;
  }, [dict, L]);
  return { ...L, t, rules: RELIEF_RULES[L.lang] || RELIEF_RULES.en };
}

